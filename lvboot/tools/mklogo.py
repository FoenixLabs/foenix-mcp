#!/usr/bin/env python3
"""mklogo.py - turn a PNG into an LVGL 8-bit indexed image (src/<name>.c) for the A2560Me LVGL boot loader.

  python tools/mklogo.py                     both logos with their usual settings
  python tools/mklogo.py IN.png NAME WIDTH [crop]

A transparent PNG is laid on the loader's background colour; 'crop' first cuts it to its non-transparent part.
The result is a 256-colour palette + one byte per pixel (a quarter of a 16-bit image). The function
`const lv_img_dsc_t * NAME_get(void)` returns the image.
"""
import sys
from PIL import Image

BG565 = 0x1083                      # must match BG565 in src/menu.c

def c565_to_888(c):
    r, g, b = (c >> 11) & 31, (c >> 5) & 63, c & 31
    return (r << 3 | r >> 2, g << 2 | g >> 4, b << 3 | b >> 2)

def make(src_png, name, width, crop):
    src = Image.open(src_png).convert('RGBA')
    if crop:
        src = src.crop(src.getchannel('A').getbbox())
    h = round(src.height * width / src.width)
    src = src.resize((width, h), Image.LANCZOS)
    bg = Image.new('RGBA', src.size, c565_to_888(BG565) + (255,))
    img = Image.alpha_composite(bg, src).convert('RGB')
    q = img.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG)
    pal = q.getpalette()[:768]
    pal += [0] * (768 - len(pal))
    px = q.tobytes()
    out = ['/* %s.c - generated by tools/mklogo.py from %s: %d x %d, 8-bit indexed */' % (name, src_png, width, h),
           '#include "lvgl.h"', '', 'static const uint8_t %s_map[] = {' % name,
           '    /* palette: 256 x { blue, green, red, alpha } (lv_color32_t) */']
    for i in range(256):
        r, g, b = pal[3 * i:3 * i + 3]
        out.append('    0x%02X, 0x%02X, 0x%02X, 0xFF,' % (b, g, r))
    out.append('    /* pixels */')
    for i in range(0, len(px), 24):
        out.append('    ' + ' '.join('0x%02X,' % v for v in px[i:i + 24]))
    out += ['};', '', 'static lv_img_dsc_t %s_dsc;' % name, '',
            'const lv_img_dsc_t * %s_get(void)' % name, '{',
            '    %s_dsc.header.always_zero = 0;' % name,
            '    %s_dsc.header.cf = LV_IMG_CF_INDEXED_8BIT;' % name,
            '    %s_dsc.header.w = %d;' % (name, width),
            '    %s_dsc.header.h = %d;' % (name, h),
            '    %s_dsc.data_size = sizeof(%s_map);' % (name, name),
            '    %s_dsc.data = %s_map;' % (name, name),
            '    return &%s_dsc;' % name, '}', '']
    open('src/%s.c' % name, 'w').write('\n'.join(out))
    print('src/%s.c: %d x %d, %d bytes of data' % (name, width, h, 1024 + len(px)))

if len(sys.argv) > 3:
    make(sys.argv[1], sys.argv[2], int(sys.argv[3]), len(sys.argv) > 4 and sys.argv[4] == 'crop')
else:
    make('assets/foenix_labs_logo.png', 'logo', 300, True)
    make('assets/violetbsd_logo.png', 'violet_logo', 150, False)
