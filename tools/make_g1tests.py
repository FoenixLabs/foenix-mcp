"""make_g1tests.py - turn the Gen1 board test programs (E:\\GEN1_ACTIVE_FPGA_Work\\host: dactest, gdmatest, blittest)
into MCP modules src\\cli\\g1t_dac.c / g1t_gdma.c / g1t_blit.c (2026-11-06, MCP 2.0.22). The test code itself is kept as
it was proven on the board; only the frame changes:
  - the results block ($0038_0200 / $0038_0300) becomes the arrays g1t_r[] / g1t_d[] (g1tests.h);
  - test_main(void) becomes g1t_<name>_main(void) (the caller puts the mode in R(0) first, as the host scripts did);
  - an endless "for (;;) {" loop runs until the deadline g1t_end (timers_jiffies, 60 Hz); "for (;;) ;" returns;
  - blittest's variadic T(...) macro is expanded (VBCC without -c99).
Run it again after a change to a host test."""
import re, os
HOST = r'E:\GEN1_ACTIVE_FPGA_Work\host'
OUT = r'E:\FoenixMCP_Gen1\src\cli'
TESTS = [('dac', r'dactest\dactest.c'), ('gdma', r'gdmatest\gdmatest.c'), ('blit', r'blittest\blittest.c')]

for name, rel in TESTS:
    s = open(os.path.join(HOST, rel)).read()
    s = s.replace('\r\n', '\n')
    s = re.sub(r'typedef unsigned long u32;\ntypedef unsigned short u16;\ntypedef unsigned char u8;\n', '', s)
    s = re.sub(r'#define R\(o\)\s+\(\*\(volatile u32 \*\)\(0x00380200 \+ \(o\)\)\)', '#define R(o)    (g1t_r[(o) >> 2])', s)
    s = re.sub(r'#define D\(k\)\s+\(\*\(volatile u32 \*\)\(0x00380300 \+ 4 \* \(k\)\)\)', '#define D(k)    (g1t_d[(k)])', s)
    assert 'g1t_r[' in s, name
    n_main = s.count('int test_main(void)')
    assert n_main == 1, (name, n_main)
    s = s.replace('int test_main(void)', 'int g1t_%s_main(void)' % name)
    s = s.replace('for (;;) ;', 'return 0;')
    s = s.replace('for (;;) {', 'while (timers_jiffies() < g1t_end) {')
    assert 'for (;;)' not in s, name
    if name == 'blit':
        m = re.search(r'#define T\(t, \.\.\.\) do \{ u32 b_ = checked\(t, __VA_ARGS__\); D\(8 \+ 2 \* \(t\)\) = B\(0x24\); D\(9 \+ 2 \* \(t\)\) = b_; \} while \(0\)\n', s)
        assert m, 'T macro'
        s = s[:m.start()] + s[m.end():]
        def expand(mm):
            t, rest = mm.group(1), mm.group(2)
            return '{ u32 b_ = checked(%s, %s); D(8 + 2 * (%s)) = B(0x24); D(9 + 2 * (%s)) = b_; }' % (t, rest, t, t)
        s, k = re.subn(r'\bT\((\d+), (.*?)\);', expand, s)
        assert k > 10, ('T uses', k)
    hdr = ('/* GENERATED by tools/make_g1tests.py from %s - edit the host test, then run the script again. */\n'
           '#include "g1tests.h"\n' % rel.replace('\\', '/'))
    open(os.path.join(OUT, 'g1t_%s.c' % name), 'w', newline='\n').write(hdr + s)
    print('g1t_%s.c written' % name)
